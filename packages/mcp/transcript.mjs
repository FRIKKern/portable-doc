import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { FAKE_TOKEN, startFakeReader } from './test/fake-reader.mjs';

const BIN = fileURLToPath(new URL('bin/portable-doc-mcp.mjs', import.meta.url));
const OUT = fileURLToPath(new URL('TRANSCRIPT.md', import.meta.url));

export const SAMPLE = {
  title: 'Release notes',
  blocks: [
    { id: 'rn-heading', type: 'heading', level: 9, text: 'The render path' },
    { id: 'rn-banner', type: 'banner', text: 'Heads up' },
  ],
};

const OPS = [
  { op: 'patch-block', id: 'rn-heading', patch: { level: 2 } },
  {
    op: 'replace-block',
    id: 'rn-banner',
    block: { id: 'rn-callout', type: 'callout', tone: 'warn', title: 'Heads up', content: [{ type: 'text', value: 'This is a warning callout body.' }] },
  },
  { op: 'append-block', block: { id: 'rn-divider', type: 'divider' } },
];

const json = (value) => ['```json', JSON.stringify(value, null, 2), '```'].join('\n');

export async function transcript() {
  const reader = await startFakeReader();
  const client = new Client({ name: 'transcript', version: '0.0.0' });
  const transport = new StdioClientTransport({ command: process.execPath, args: [BIN], env: { BARKPARK_URL: reader.base, BARKPARK_TOKEN: FAKE_TOKEN }, stderr: 'pipe' });
  const lines = [
    '# Transcript',
    '',
    '```',
    'SDK Client ──stdio──► bin/portable-doc-mcp.mjs ──POST /v1/plugins/bulldocs/render──► BARKPARK_URL',
    '                        validate · explain · apply_ops · render        (here: test/fake-reader.mjs,',
    '                                                                         golden reader output)',
    '```',
    '',
    'Generated by `node packages/mcp/transcript.mjs`; `npm run check` fails when this file is stale. One sample doc, four tools, the real `@modelcontextprotocol/sdk` client over stdio.',
  ];
  const call = async (step, name, args) => {
    const result = await client.callTool({ name, arguments: args });
    lines.push('', `## ${step}`, '', `\`${name}\``, '', json(args), '', '→', '', json(result.structuredContent));
    return result.structuredContent;
  };
  try {
    await client.connect(transport);
    const { tools } = await client.listTools();
    lines.push('', '## 0. tools/list', '', json(tools.map((t) => t.name)));
    const checked = await call('1. Validate the sample', 'validate', { doc: SAMPLE });
    await call('2. Explain what is wrong', 'explain', { errors: checked.errors, doc: SAMPLE });
    const applied = await call('3. Apply ops that fix it', 'apply_ops', { doc: SAMPLE, ops: OPS });
    await call('4. Validate the result', 'validate', { doc: applied.doc });
    await call('5. Render it through the reader', 'render', { doc: applied.doc });
    lines.push('', '## What the reader received', '', json(reader.requests.map(({ method, url, body }) => ({ method, url, body: JSON.parse(body) }))));
  } finally {
    await client.close();
    await reader.close();
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, await transcript());
  console.log(`wrote ${OUT}`);
}
